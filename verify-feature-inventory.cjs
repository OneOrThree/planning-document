/* 사용자 데이터를 건드리지 않는 문서 목록 검증. 앱 기능 전체의 E2E 검증과 다르다. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const {chromium}=require('playwright');
const base=(process.env.BASE_URL || 'http://127.0.0.1:4173/').replace(/\/$/, '');
const root=__dirname;
let checks=0;
function check(ok,message){assert.ok(ok,message);checks++;}
(async()=>{
  const sandbox={window:{}};
  for(const file of ['feature-inventory-data.js','ia-manifest.js'])vm.runInNewContext(fs.readFileSync(path.join(__dirname,file),'utf8'),sandbox);
  const data=sandbox.window.GachisupFeatureInventory,ia=sandbox.window.GachisupIA;
  const ids=data.features.map(f=>f.id),screens=[...ia.screens,...ia.sheets];
  const activeScreens=screens.filter(s=>!data.retiredScreens[s.id]);
  check(new Set(ids).size===ids.length,'기능 ID 중복 없음');
  check(data.groups.length===16&&data.features.length===170,'현재 목록 16개 영역 / 170개 항목');
  check(!ids.includes('I07'),'별도 콕찌르기는 현행 기능에서 제외');
  check(Object.keys(data.retiredScreens).join() === 'po3'&&activeScreens.length===44,'기존 콕찌르기 화면만 제외 이력으로 분리');
  const letter=data.features.find(f=>f.id==='I06');
  check(letter.decision==='chosen'&&letter.proof==='pending'&&letter.title.includes('우리 섬에 편지 쓰기'),'편지 통합은 사용자 결정·실제 연결 전');
  check(letter.note.includes('개인 수신자 선택')&&letter.note.includes('실제 전송'),'섬 전체 편지·개인 수신자 없음·실제 전송 경계');
  for(const f of data.features){
    check(Boolean(data.decisions[f.decision]&&data.proofs[f.proof]),f.id+' 상태 유효');
    check(f.sources.length>0&&f.sources.every(s=>data.sources[s]),f.id+' 근거 키 유효');
    check(f.screens.every(id=>screens.some(s=>s.id===id)),f.id+' IA 연결 유효');
    check(f.screens.every(id=>!data.retiredScreens[id]),f.id+' 제외된 화면을 현행 기능에 연결하지 않음');
    check(Boolean(f.title&&f.action&&f.world&&f.note),f.id+' 필수 설명 있음');
    if(f.studio)check(fs.existsSync(path.join(__dirname,f.studio)),f.id+' 작업실 있음');
  }
  for(const source of Object.values(data.sources))check(source.repository==='phone'?source.path.startsWith('app/'):fs.existsSync(path.join(root,source.path)),source.path+' 로컬 근거 존재 또는 별도 원앱 출처 명시');
  for(const screen of activeScreens)check(data.features.some(f=>f.screens.includes(screen.id)),screen.id+' 누락 없이 매핑');
  const browser=await chromium.launch({headless:true});
  const errors=[];
  fs.mkdirSync(path.join(__dirname,'tmp/verification/feature-inventory'),{recursive:true});
  try{
    for(const width of [1440,768,390,320]){
      const context=await browser.newContext({viewport:{width,height:width===1440?1080:900},reducedMotion:'reduce'});
      const page=await context.newPage();
      page.on('pageerror',e=>errors.push(e.message));
      page.on('response',r=>{if(r.url().startsWith(base)&&r.status()>=400)errors.push(r.status()+' '+r.url());});
      await page.goto(base+'/feature-inventory.html',{waitUntil:'networkidle'});
      check(await page.locator('#journey-view').isVisible(),width+' 기본은 유저 저니');
      await page.locator('[data-planning-tab=wrapping]').click();
      check(await page.locator('.overview-card:visible').count()===8,width+' 기능 표현은 큰 기능 8개');
      check(await page.locator('#detail-view').isHidden(),'세부 목록은 첫 화면에서 숨김');
      check(await page.locator('.overview-more[open]').count()===0,'하위 영역은 기본 접힘');
      check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),width+' 큰 기능 가로 넘침 없음');
      const mapping=await page.evaluate(()=>GachisupFeatureOverview.flatMap(g=>g.groups));
      check(new Set(mapping).size===15&&mapping.length===15,'기존 15개 영역을 빠짐·중복 없이 묶음, 후보는 별도');
      if([1440,390].includes(width))await page.screenshot({path:path.join(__dirname,'tmp/verification/feature-inventory',width+'-overview.png'),fullPage:true});
      await page.locator('[data-overview=grow] summary').focus();await page.keyboard.press('Enter');
      check(await page.locator('[data-overview=grow] .overview-more').getAttribute('open')!==null,'큰 기능 키보드 펼치기');
      await page.locator('[data-overview=grow] a').first().click();
      check(await page.locator('#detail-view').isVisible(),'묶음에서 세부 목록 진입');
      check(await page.locator('#group-filter').inputValue()==='together','묶음에서 정확한 영역 연결');
      await page.locator('[data-planning-tab=wrapping]').click();
      check(await page.locator('.overview-card:visible').count()===8,'큰 기능으로 복귀');
      await page.locator('[data-mode=detail]').click();
      check(await page.locator('#group-filter').inputValue()==='together','탭 복귀 시 이전 필터 유지');
      await page.locator('#reset').click();
      const storage=await page.evaluate(()=>JSON.stringify({...localStorage}));
      const rows=()=>page.locator('.feature:visible');
      const noOverflow=async()=>check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),width+' 가로 넘침 없음');
      const reset=async()=>{await page.locator('#reset').click();check(await rows().count()===data.features.length,'초기화하면 전체');};
      const capture=async suffix=>{if([1440,390].includes(width))await page.screenshot({path:path.join(__dirname,'tmp/verification/feature-inventory',width+'-'+suffix+'.png')});};
      check(await rows().count()===170,width+' 처음부터 전체 기능 노출');
      check(await page.locator('#feature-I07').count()===0,'콕찌르기 행 제거');
      check(await page.locator('.feature-group:visible').count()===16,'모든 영역 노출');
      check(await page.locator('#total-screens').textContent()==='44','현행 연결 화면·시트 수 44');
      await noOverflow();await capture('all');
      await page.locator('#search').fill('포모도로');
      check(await rows().count()>0,'과거 앱 기능 검색');
      check(await page.locator('#feature-D06').isVisible(),'수정본 포모도로 노출');
      check(await page.locator('#search').evaluate(e=>document.activeElement===e),'검색해도 입력 포커스 유지');
      await page.reload();
      check(await page.locator('#search').inputValue()==='포모도로','새로고침 검색 유지');
      await page.locator('#feature-D06 summary').click();
      check(await page.locator('#feature-D06').getAttribute('open')!==null,'근거 펼치기');
      check((await page.locator('#feature-D06 .source-list').textContent()).includes('04-island-growth.html'),'실제 원앱 근거 경로 노출');
      await noOverflow();await capture('legacy');
      await page.locator('#search').fill('뗏목');
      check(await page.locator('#feature-N06').isVisible(),'뗏목 교체 상태 검색');
      await page.locator('#feature-N06 summary').click();
      check((await page.locator('#feature-N06 .feature-note').textContent()).includes('뗏목→돛단배→배'),'개인 배 단계 방향과 구현 경계 명시');
      check(await page.locator('#feature-N06 a[href="revisions/07-personal-shared-decoration.html"]').count()===1,'최신 개인 배 기획 연결');
      await noOverflow();
      await page.locator('#search').fill('검증용존재하지않는기능');
      check(await rows().count()===0,'검색 0개');
      check(await page.locator('#empty').isVisible(),'빈 검색 안내');
      await page.locator('#empty-reset').click();
      check(await rows().count()===170,'빈 결과에서 복구');
      await page.locator('[data-view=decide]').click();
      check(await rows().count()===data.features.filter(f=>['proposal','review'].includes(f.decision)).length,'결정할 항목 필터');
      await page.reload();check(await page.locator('[data-view=decide]').getAttribute('aria-pressed')==='true','빠른 필터 새로고침 유지');
      await page.locator('[data-view=legacy]').click();
      check(await rows().count()===data.features.filter(f=>f.decision==='review').length,'원앱 승계 필터');
      await page.locator('[data-view=pending]').click();
      check(await rows().count()===data.features.filter(f=>f.proof==='pending').length,'연결 전 필터');
      await reset();
      await page.locator('#group-filter').selectOption('focus');
      check(await rows().count()===19,'집중 19개 영역 필터');
      check(await page.locator('.feature-domain:visible').count()===4,'집중 영역 4개 가치 묶음');
      check(await page.locator('#feature-D15').count()===0,'기본 낚싯대 제외');
      check(await page.locator('#feature-D18').isVisible()&&await page.locator('#feature-D19').isVisible(),'스크린타임·후기 별도 항목');
      await page.locator('#decision-filter').selectOption('chosen');
      check(await rows().count()===data.features.filter(f=>f.group==='focus'&&f.decision==='chosen').length,'복합 필터');
      await page.locator('#toggle-details').click();
      check(await rows().evaluateAll(es=>es.every(e=>e.open)),'표시 항목 모두 펼치기');
      await noOverflow();
      await page.locator('#toggle-details').click();
      check(await rows().evaluateAll(es=>es.every(e=>!e.open)),'표시 항목 모두 접기');
      await reset();
      await page.locator('#feature-A01 summary').focus();await page.keyboard.press('Enter');
      check(await page.locator('#feature-A01').getAttribute('open')!==null,'키보드로 상세 열기');
      await page.locator('.reading-guide summary').click();await noOverflow();
      check(await page.locator('.guide-grid').isVisible(),'상태 정의 확인');
      const unsafe=await page.locator('a[target="_blank"]').evaluateAll(as=>as.some(a=>!a.rel.includes('noopener')));
      check(!unsafe,'새 창 링크 안전 속성');
      check(await page.evaluate(()=>JSON.stringify({...localStorage}))===storage,'제품 저장 데이터 변경 없음');
      await page.goto(base+'/feature-inventory.html?group=start#feature-N06',{waitUntil:'networkidle'});
      check(await page.locator('#feature-N06').isVisible(),'직접 기능 링크는 숨겨진 필터 복구');
      check(await page.locator('#feature-N06').getAttribute('open')!==null,'직접 기능 링크 펼침');
      await noOverflow();
      await page.locator('#group-filter').selectOption('focus');
      await page.reload();check(await rows().count()===19,'항목 바로가기 이후에도 새 필터 유지');
      await reset();await page.reload();check(await rows().count()===170,'필터 초기화 후에도 세부 보기 유지');
      await page.goto(base+'/eli5-journey.html',{waitUntil:'networkidle'});
      await noOverflow();
      await page.locator('.view-nav a[href="feature-inventory.html"]').click();
      check(new URL(page.url()).pathname===new URL(base+'/feature-inventory.html').pathname,'ELI5에서 전체 목록 진입');
      check(await page.locator('#journey-view').isVisible(),'ELI5 연결은 새 기획 작업대의 유저 저니부터 표시');
      check(await page.locator('[role=tab]').count()===6,'작업대의 여섯 문서 진입점 노출');
      await noOverflow();
      await context.close();
    }
    const context=await browser.newContext();
    for(const file of ['feature-inventory.html','feature-inventory-notes.md','eli5-journey.html','rig.html','walk.html','revisions/04-island-growth.html','revisions/07-personal-shared-decoration.html','growth-decoration-revision-20260911.md','story-loop-plan.md']){
      const response=await context.request.get(base+'/'+file);check(response.ok(),file+' 링크 응답');
    }
    for(const screen of screens){const response=await context.request.get(base+'/ia.html?screen='+screen.id);check(response.ok(),screen.id+' IA 응답');}
    await context.close();
    check(errors.length===0,'브라우저 오류 없음: '+errors.join(', '));
    console.log(JSON.stringify({checks,features:data.features.length,groups:data.groups.length,mappedScreens:activeScreens.length,retiredScreens:Object.keys(data.retiredScreens),errors,screenshots:'tmp/verification/feature-inventory'},null,2));
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
