const {chromium}=require('playwright');
const assert=require('node:assert/strict'),fs=require('node:fs');
const dir=__dirname+'/screenshots/cooperative';fs.mkdirSync(dir,{recursive:true});
let count=0;const errors=[],ok=(v,label)=>{assert.ok(v,label);console.log('✓ '+label);count++;};
(async()=>{
  const browser=await chromium.launch({headless:true});
  try{
    for(const width of [390,320,1440]){
      const context=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce'}),p=await context.newPage();
      p.on('pageerror',e=>errors.push(e.message));
      await p.clock.setFixedTime(new Date('2026-09-09T20:00:00+09:00'));
      await p.goto(((process.env.BASE_URL || 'http://127.0.0.1:4173/').replace(/\/$/, '') + '/index.html?ia=cp1&role=OWNER'),{waitUntil:'networkidle'});
      await p.waitForFunction(()=>document.body.dataset.iaScreen==='cp1');
      const shot=async name=>{await p.screenshot({path:dir+'/'+width+'-'+name+'.png'});ok(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1&&!['.panel-content','.panel-footer'].some(s=>{const e=document.querySelector(s);return e&&e.scrollWidth>e.clientWidth+1;})),width+' '+name+' 가로 넘침 없음');};
      await shot('project');
      await p.locator('[data-coop=contribute]').click();
      ok(await p.locator('.coop-contribution-banner').count()===1,width+' 기본 집중에 프로젝트 기여 선택 표시');
      await p.locator('[data-action=start]:visible').click();
      await p.clock.setFixedTime(new Date('2026-09-09T20:01:00+09:00'));
      await p.locator('#focus-footer [data-action=finish]').click();await p.locator('[data-action=confirm-finish]').click();
      ok(await p.evaluate(()=>GachisupVillage.model.placeProject().seconds===60),width+' 실제 1분 기여 적립');
      await p.locator('#building-panel [data-coop=open]:visible').click();await p.locator('[data-coop=preview]').click();
      ok(await p.evaluate(()=>GachisupVillage.model.placeProject().seconds===60&&GachisupVillage.model.placeProject().ready),width+' 수치를 조작하지 않고 완성 상태 열기');
      await p.locator('[data-coop=create]').click();await shot('create');
      await p.locator('[data-coop=now]').click();await p.locator('[form=coop-meeting-form]').click();
      ok(await p.evaluate(()=>GachisupVillage.model.get().quests.some(q=>q.placeId==='pier')),width+' 시간·장소·액션 약속을 실제 게시판 모델에 저장');
      await p.locator('[data-coop=join]').click();await shot('meeting');
      await p.locator('#coop-record-tag').selectOption('독서');await p.locator('[data-coop=start-meeting]').click();
      await p.waitForFunction(()=>document.getElementById('village-app').dataset.activity==='gather');
      await p.waitForFunction(()=>!!document.querySelector('#rest-boat[data-cooperative-time]'));
      await shot('focus');
      ok(await p.evaluate(()=>GachisupVillage.state.session.tag==='독서'&&GachisupVillage.state.session.worldAction==='fishing'),width+' 현실 기록과 공동 액션 분리');
      ok((await p.locator('.focus-company').innerText()).includes('예시'),width+' 동료 연출은 실제 접속과 구분');
      await p.reload({waitUntil:'networkidle'});
      await p.waitForFunction(()=>document.getElementById('village-app').dataset.activity==='gather');
      ok(await p.locator('#rest-boat').getAttribute('data-cooperative')==='true',width+' 새로고침해도 공동 액션 유지');
      await p.clock.setFixedTime(new Date('2026-09-09T20:03:00+09:00'));
      await p.locator('#focus-footer [data-action=finish]').click();await p.locator('[data-action=confirm-finish]').click();
      await shot('result');await p.locator('#building-panel [data-coop=open]:visible').click();await shot('memory');
      ok(await p.evaluate(()=>GachisupVillage.model.placeMemories().length===1),width+' 종료 후 같은 부두에 기억 남음');
      await p.reload({waitUntil:'networkidle'});await p.waitForFunction(()=>document.body.dataset.iaScreen==='cp1');
      ok(await p.locator('.coop-memory li').count()===1,width+' 부두·약속·기억 새로고침 복원');
      await p.locator('[data-activity=rest]:visible').click();await p.locator('[data-action=start]:visible').click();
      ok(await p.evaluate(()=>GachisupVillage.state.session.kind==='rest'&&!GachisupVillage.state.session.questId),width+' 기본 무료 휴식 낚시 독립 유지');
      await context.close();
    }
    const context=await browser.newContext({viewport:{width:1440,height:1000}}),p=await context.newPage();p.on('pageerror',e=>errors.push(e.message));
    await p.goto(((process.env.BASE_URL || 'http://127.0.0.1:4173/').replace(/\/$/, '') + '/mobile.html?screen=cp1'),{waitUntil:'networkidle'});
    ok(await p.locator('#mobile-screen option[value=cp1]').count()===1,'모바일 화면 목록에 공동 장소 추가');
    const f=p.frameLocator('#mobile-preview');await f.locator('[data-coop=preview]').click();await f.locator('[data-coop=create]').click();await f.locator('[data-coop=now]').click();await f.locator('[form=coop-meeting-form]').click();await f.locator('[data-coop=join]').click();await f.locator('[data-coop=start-meeting]').click();
    await f.locator('[data-action=skip-entry]').click();
    await f.locator('#rest-boat[data-cooperative=true]').waitFor({state:'visible'});
    const t=await f.locator('#rest-boat').getAttribute('data-cooperative-time');await p.waitForTimeout(500);
    ok(await f.locator('#rest-boat').getAttribute('data-cooperative-time')!==t,'공동 낚시 메시 리그 시간 진행');
    await f.locator('[data-action=motion]').click();const paused=await f.locator('#rest-boat').getAttribute('data-cooperative-time');await p.waitForTimeout(350);
    ok(await f.locator('#rest-boat').getAttribute('data-cooperative-time')===paused,'움직임 줄이기에 공동 낚시 리그 정지');
    await p.locator('#landscape').click();await p.screenshot({path:dir+'/mobile-landscape.png'});
    ok(await f.locator('#rest-boat').getAttribute('data-cooperative')==='true','모바일 가로 회전에도 같은 공동 활동 유지');
    await context.close();ok(errors.length===0,'브라우저 오류 없음 '+errors.join(';'));
    console.log(count+'개 공동 장소 브라우저 검증 통과');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
